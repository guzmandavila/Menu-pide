// Node 22+ and jsdom: npm install --no-save --package-lock=false jsdom@26
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const {JSDOM} = require('jsdom');
const source = fs.readFileSync(path.join(__dirname, '..', 'app.js'), 'utf8');
const dom = new JSDOM('<body><button id="category"><img src="banner.jpg" alt="Banner"><span>Ver categoría</span></button><img id="logo" src="logo.png" alt="Clowder"><div id="menu"></div></body>', {url:'https://example.test/', runScripts:'outside-only'});
const {window} = dom;
window.HTMLDialogElement.prototype.showModal = function(){this.open = true;};
window.HTMLDialogElement.prototype.close = function(){this.open = false;};
const start = source.indexOf('const productPhotoDialog =');
const end = source.indexOf("document.getElementById('cartbar').addEventListener", start);
assert.ok(start >= 0 && end > start);
window.eval(source.slice(start, end));
const doc = window.document;
const viewer = doc.querySelector('dialog');
const photo = viewer.querySelector('img');
let categoryClicks = 0;
doc.getElementById('category').addEventListener('click', () => categoryClicks++);
async function main(){
  const banner = doc.querySelector('#category img');
  banner.click();
  assert.equal(viewer.open, true);
  assert.equal(photo.getAttribute('src'), 'https://example.test/banner.jpg');
  assert.equal(categoryClicks, 0, 'A photo must not navigate its parent category');
  assert.equal(banner.getAttribute('role'), 'button');
  viewer.querySelector('.product-photo-zoom').click();
  assert.ok(viewer.classList.contains('is-zoomed'));
  assert.equal(viewer.querySelector('.product-photo-zoom').getAttribute('aria-pressed'), 'true');
  viewer.querySelector('.product-photo-close').click();
  assert.equal(viewer.open, false);
  doc.querySelector('#category span').click();
  assert.equal(categoryClicks, 1, 'Category text must still navigate');
  doc.getElementById('logo').dispatchEvent(new window.KeyboardEvent('keydown', {key:'Enter', bubbles:true, cancelable:true}));
  assert.equal(viewer.open, true);
  assert.equal(photo.alt, 'Clowder');
  assert.equal(viewer.classList.contains('is-zoomed'), false, 'Reset zoom for the next photo');
  viewer.close();
  const dynamic = doc.createElement('img');
  dynamic.src = 'new-product.jpg';
  dynamic.alt = 'Nuevo producto';
  doc.getElementById('menu').append(dynamic);
  await new Promise(resolve => window.setTimeout(resolve, 0));
  dynamic.dispatchEvent(new window.KeyboardEvent('keydown', {key:' ', bubbles:true, cancelable:true}));
  assert.equal(viewer.open, true, 'Dynamic product images must support the viewer');
  assert.equal(photo.alt, 'Nuevo producto');
  assert.equal(photo.hasAttribute('role'), false, 'Viewer photo must not open itself');
  viewer.close();
  // Carousel capture handlers suppress clicks after a drag before the image runs.
  const track = doc.getElementById('menu');
  track.addEventListener('click', event => event.stopImmediatePropagation(), {capture:true, once:true});
  dynamic.click();
  assert.equal(viewer.open, false, 'A suppressed carousel drag must not open the viewer');
  dynamic.click();
  assert.equal(viewer.open, true);
  viewer.dispatchEvent(new window.MouseEvent('click', {bubbles:true}));
  assert.equal(viewer.open, false, 'Backdrop click closes the viewer');
  console.log('Photo viewer checks passed: banners, logos, dynamic photos, keyboard, zoom, category actions and drag suppression.');
}
main().catch(error => {console.error(error);process.exitCode = 1;}).finally(() => window.close());
